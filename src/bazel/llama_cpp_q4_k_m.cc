#include "base/win32/utf8_console_argv.h"
#include "llama.h"

namespace {

int MainUtf8(int argc, char** argv) {
  if (argc != 3) {
    return 2;
  }

  llama_backend_init();
  llama_model_quantize_params params = llama_model_quantize_default_params();
  params.ftype = LLAMA_FTYPE_MOSTLY_Q4_K_M;
  const uint32_t result = llama_model_quantize(argv[1], argv[2], &params);
  llama_backend_free();
  return result == 0 ? 0 : 1;
}

}  // namespace

int wmain(int argc, wchar_t** argv) {
  mozc::win32::Utf8ConsoleArgv utf8_argv(argc, argv);
  return MainUtf8(utf8_argv.argc(), utf8_argv.argv());
}
